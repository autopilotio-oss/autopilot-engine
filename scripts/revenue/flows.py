"""Generate the auditable funnel map: keyword -> reply link -> guide -> email sequence -> offer -> checkout status.
python3 scripts/revenue/flows.py  -> revenue-engine-v2/FLOWS_MAP.md"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catalog

ROOT = catalog.ROOT
SEQ = {"money": ("2951378", "Money guides · Agents"), "tiktok": ("2951663", "TikTok guides · Agents"), "business": ("2951307", "Welcome · Business Brain to Workspace")}
TIKTOK = {"video", "shop", "sell"}
BUSINESS = {"brain", "workspace", "frontdesk", "home"}


def seq_for(source):
    if source in TIKTOK:
        return SEQ["tiktok"]
    if source in BUSINESS:
        return SEQ["business"]
    return SEQ["money"]


def main():
    cat = catalog.build()
    by_guide = {}
    for o in cat["offers"]:
        for g in o["guides"]:
            by_guide.setdefault(g["guide"], []).append(o)
    rows = []
    for k in cat["keywords"]:
        for path in k["links"] or ["(none)"]:
            m = re.match(r"g/([^/]+)/", path)
            guide = m.group(1) if m else path.strip("/") or "home"
            offers = by_guide.get(guide, [])
            if not offers and guide in ("brain", "workspace"):
                offers = [o for o in cat["offers"] if o["offer_id"] == "workspace"]
            sid, sname = seq_for(guide)
            for o in offers or [None]:
                rows.append((k["keyword"], "/" + path, guide, f"{sname} ({sid})",
                             o["offer_id"] if o else "none", o["status"] if o else "n/a",
                             "ManyChat: UNVERIFIED (no API access)"))
    out = ["# Funnel map (generated)", "", "Generated by scripts/revenue/flows.py from config/keywords.json, tools/guides, products/ and docs/live.json.",
           "Email routing is done by the 'Kit welcome sync' scheduled task using the subscriber's `source` field.", "",
           "| Keyword | Reply link | Guide (Kit source) | Email sequence | Offer | Offer status | Comment automation |", "|---|---|---|---|---|---|---|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    open(os.path.join(ROOT, "revenue-engine-v2", "FLOWS_MAP.md"), "w").write("\n".join(out) + "\n")
    print(f"{len(rows)} routes mapped")


if __name__ == "__main__":
    main()
